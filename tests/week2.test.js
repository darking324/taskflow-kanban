const {JSDOM}=require('jsdom');const fs=require('fs');const dir=process.argv[2];
const html=fs.readFileSync(dir+'/index.html','utf8').replace('<script src="script.js"></script>','');
const dom=new JSDOM(html,{runScripts:'outside-only'});const w=dom.window,d=w.document;
let confirmAns=true;w.confirm=()=>confirmAns;w.prompt=()=> 'Renamed task';
w.eval(fs.readFileSync(dir+'/script.js','utf8'));
const cnt=s=>d.querySelector(`.column[data-status="${s}"] .task-count`).textContent;
const ok=(c,m)=>{console.log((c?'PASS':'FAIL')+' '+m);if(!c)process.exitCode=1};
ok(cnt('todo')=='2'&&cnt('progress')=='2'&&cnt('done')=='2','initial counts 2/2/2');
d.querySelector('#task-input').value='Test task';d.querySelector('#priority-select').value='high';
d.querySelector('.add-task-form').dispatchEvent(new w.Event('submit',{cancelable:true}));
const todo=d.querySelector('.column[data-status="todo"]');const last=[...todo.querySelectorAll('.task-card')].pop();
ok(cnt('todo')=='3'&&last.querySelector('.task-title').textContent=='Test task'&&last.querySelector('.priority-high'),'add task to To Do with priority');
ok(d.querySelector('#task-input').value=='','input cleared');
last.querySelector('.move-button').click();ok(cnt('todo')=='2'&&cnt('progress')=='3','move to In Progress, counts update');
last.querySelector('.move-button').click();ok(cnt('progress')=='2'&&cnt('done')=='3','move to Done');
last.querySelector('.edit-button').click();ok(last.querySelector('.task-title').textContent=='Renamed task','edit title');
confirmAns=false;last.querySelector('.delete-button').click();ok(cnt('done')=='3','delete cancelled keeps card');
confirmAns=true;last.querySelector('.delete-button').click();ok(cnt('done')=='2','delete confirmed removes card');
d.querySelector('#task-input').value='   ';d.querySelector('.add-task-form').dispatchEvent(new w.Event('submit',{cancelable:true}));ok(cnt('todo')=='2','blank title ignored');
